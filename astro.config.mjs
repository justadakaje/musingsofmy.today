// @ts-check
import { defineConfig } from 'astro/config';
import mdx from '@astrojs/mdx';
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { SECTIONS } from './src/site.ts';

/**
 * Writes dist/_redirects and dist/_headers (Cloudflare Workers static assets, same format as
 * Pages) from the section map in src/site.ts, so the old WordPress category URLs follow any
 * future section change automatically. Posts need no redirects: their URLs are unchanged.
 * Cloudflare wants static rules before dynamic ones (splats/placeholders), and allows
 * 2,000 static + 100 dynamic.
 * @returns {import('astro').AstroIntegration}
 */
function cloudflareRedirects() {
  return {
    name: 'cloudflare-redirects',
    hooks: {
      'astro:build:done': async ({ dir }) => {
        const statics = [
          '# Feeds: WordPress served RSS at /feed/; readers follow a 301.',
          '/feed /rss.xml 301',
          '/feed/ /rss.xml 301',
          '/comments/feed/ /rss.xml 301',
          '# Old category archives → the five sections (PLAN.md).',
          '/category/podcast/ /podcasts/ 301',
          ...SECTIONS.flatMap((s) => s.categories.map((c) => `/category/${c.path}/ /section/${s.id}/ 301`)),
          '/wp-login.php / 302',
        ];
        const dynamics = [
          '# Anything under an old category (child categories, feeds, page/2/) → its section.',
          '/category/podcast/* /podcasts/ 301',
          ...SECTIONS.flatMap((s) => s.categories.map((c) => `/category/${c.path}/* /section/${s.id}/ 301`)),
          '/feed/* /rss.xml 301',
          '/tag/:tag/feed/ /rss.xml 301',
          '/tag/:tag/page/* /tag/:tag/ 301',
          '/*/feed/ /rss.xml 301',
          '# Other WordPress archives.',
          '/author/* /about/ 301',
          '/page/* /archive/ 301',
          '/wp-admin/* / 302',
        ];
        const lines = ['# Generated by astro.config.mjs at build time. Edit src/site.ts, not this file.', ...statics, ...dynamics];
        await fs.writeFile(new URL('_redirects', dir), lines.join('\n') + '\n');
        await fs.writeFile(
          new URL('_headers', dir),
          [
            '/*',
            '  X-Content-Type-Options: nosniff',
            '  Referrer-Policy: strict-origin-when-cross-origin',
            '  Permissions-Policy: interest-cohort=()',
            '/_astro/*',
            '  Cache-Control: public, max-age=31536000, immutable',
            '# workers.dev and preview URLs must not compete with the real domain in search results.',
            '# (Placeholders stop at dots, so this matches <worker>.<sub> and <preview>-<worker>.<sub>.)',
            'https://:worker.:subdomain.workers.dev/*',
            '  X-Robots-Tag: noindex',
            '',
          ].join('\n'),
        );
        console.log(`cloudflare-redirects: wrote ${lines.filter((l) => !l.startsWith('#')).length} rules to ${fileURLToPath(new URL('_redirects', dir))}`);
      },
    },
  };
}

export default defineConfig({
  site: 'https://musingsofmy.today',
  // WordPress URLs all end in a slash; keep them byte-identical.
  trailingSlash: 'always',
  build: { format: 'directory' },
  // WordPress already curled the quotes ("wptexturize"); don't do it twice.
  markdown: { smartypants: false },
  integrations: [mdx(), cloudflareRedirects()],
});
