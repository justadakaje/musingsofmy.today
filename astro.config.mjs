// @ts-check
import { defineConfig } from 'astro/config';
import mdx from '@astrojs/mdx';
import { satteri } from '@astrojs/markdown-satteri';
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { SECTIONS } from './src/site.ts';

/**
 * Writes dist/_redirects and dist/_headers (Cloudflare Workers static assets, same format as
 * Pages) from the section map in src/site.ts, so the old WordPress category URLs follow any
 * future section change automatically. Posts need no redirects: their URLs are unchanged.
 * Cloudflare wants static rules before dynamic ones (splats/placeholders), and allows
 * 2,000 static + 100 dynamic.
 * @returns {import('astro').AstroIntegration}
 */
function cloudflareRedirects() {
  return {
    name: 'cloudflare-redirects',
    hooks: {
      'astro:build:done': async ({ dir }) => {
        const statics = [
          '# Feeds: WordPress served RSS at /feed/; readers follow a 301.',
          '/feed /rss.xml 301',
          '/feed/ /rss.xml 301',
          '/comments/feed/ /rss.xml 301',
          '# Old category archives → the five sections (PLAN.md).',
          '/category/podcast/ /podcasts/ 301',
          ...SECTIONS.flatMap((s) => s.categories.map((c) => `/category/${c.path}/ /section/${s.id}/ 301`)),
          '/wp-login.php / 302',
          '/archify/dual-harness-timeline.html /archify/dual-harness-timeline/ 301',
          '/archify/config-as-code-cloudflare.html /archify/config-as-code-cloudflare/ 301',
          '/2026/11/30/get-used-to-it-part-1/ /2026/11/25/get-used-to-it-part-1/ 301',
          '/2026/11/28/the-patchpocalypse-and-the-great-tech-cascade/ /2026/11/25/the-patchpocalypse-and-the-great-tech-cascade/ 301',
        ];
        const dynamics = [
          '# Anything under an old category (child categories, feeds, page/2/) → its section.',
          '/category/podcast/* /podcasts/ 301',
          ...SECTIONS.flatMap((s) => s.categories.map((c) => `/category/${c.path}/* /section/${s.id}/ 301`)),
          '/feed/* /rss.xml 301',
          '/tag/:tag/feed/ /rss.xml 301',
          '/tag/:tag/page/* /tag/:tag/ 301',
          '/*/feed/ /rss.xml 301',
          '# Other WordPress archives.',
          '/author/* /about/ 301',
          '/page/* /archive/ 301',
          '/wp-admin/* / 302',
          '# Old image links (other sites, cached feeds, image search) to WordPress-hosted uploads.',
          '# The free musingsofmytoday.wordpress.com site keeps serving them; 302 because that is',
          '# borrowed hosting, not a permanent home.',
          '/wp-content/uploads/* https://musingsofmytoday.wordpress.com/wp-content/uploads/:splat 302',
        ];
        const lines = ['# Generated by astro.config.mjs at build time. Edit src/site.ts, not this file.', ...statics, ...dynamics];
        await fs.writeFile(new URL('_redirects', dir), lines.join('\n') + '\n');
        await fs.writeFile(
          new URL('_headers', dir),
          [
            '/*',
            // WordPress.com sent this exact HSTS policy; browsers that cached it keep insisting on
            // HTTPS for a year, so the new site keeps the same promise.
            '  Strict-Transport-Security: max-age=31536000',
            '  X-Content-Type-Options: nosniff',
            '  Referrer-Policy: strict-origin-when-cross-origin',
            '  Permissions-Policy: interest-cohort=()',
            '/_astro/*',
            '  Cache-Control: public, max-age=31536000, immutable',
            '/_discord-threads.json',
            '  X-Robots-Tag: noindex',
            '# workers.dev and preview URLs must not compete with the real domain in search results.',
            '# (Placeholders stop at dots, so this matches <worker>.<sub> and <preview>-<worker>.<sub>.)',
            'https://:worker.:subdomain.workers.dev/*',
            '  X-Robots-Tag: noindex',
            '',
          ].join('\n'),
        );

        // Emit build-time allowlist mapping published post IDs -> Discord thread IDs so
        // /api/discord/thread/:postId never accepts arbitrary Discord channel/thread IDs.
        const postsRoot = new URL('./src/content/posts/', import.meta.url);
        /** @type {Record<string, string>} */
        const threadMap = {};
        try {
          const entries = await fs.readdir(postsRoot, { withFileTypes: true });
          for (const ent of entries) {
            if (!ent.isDirectory()) continue;
            for (const ext of ['mdx', 'md']) {
              try {
                const raw = await fs.readFile(new URL(`${ent.name}/index.${ext}`, postsRoot), 'utf8');
                const fm = /^---\r?\n([\s\S]*?)\r?\n---/.exec(raw)?.[1];
                if (!fm || /^draft:\s*true\b/m.test(fm)) break;
                const tid = /^discord_thread:\s*["']?(\d{17,20})["']?/m.exec(fm)?.[1];
                if (tid) threadMap[ent.name] = tid;
                break;
              } catch {}
            }
          }
        } catch {}
        await fs.writeFile(new URL('_discord-threads.json', dir), JSON.stringify(threadMap, null, 2) + '\n');

        console.log(`cloudflare-redirects: wrote ${lines.filter((l) => !l.startsWith('#')).length} rules to ${fileURLToPath(new URL('_redirects', dir))}`);
      },
    },
  };
}

export default defineConfig({
  site: 'https://musingsofmy.today',
  // WordPress URLs all end in a slash; keep them byte-identical.
  trailingSlash: 'always',
  build: { format: 'directory' },
  // WordPress already curled the quotes ("wptexturize"); don't do it twice.
  // Also alias WoW `.toc` addon manifests to `ini` so Shiki highlights directives without warnings.
  markdown: {
    processor: satteri({ features: { smartPunctuation: false } }),
    shikiConfig: { langAlias: { toc: 'ini' } },
  },
  integrations: [mdx(), cloudflareRedirects()],
});
