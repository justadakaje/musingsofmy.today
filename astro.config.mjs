// @ts-check
import { defineConfig } from 'astro/config';
import mdx from '@astrojs/mdx';
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { SECTIONS } from './src/site.ts';

/**
 * Writes dist/_redirects (Cloudflare Pages) from the section map in src/site.ts, so the old
 * WordPress category URLs follow any future section change automatically.
 * Posts need no redirects: their URLs are unchanged.
 * @returns {import('astro').AstroIntegration}
 */
function cloudflareRedirects() {
  return {
    name: 'cloudflare-redirects',
    hooks: {
      'astro:build:done': async ({ dir }) => {
        const lines = [
          '# Generated by astro.config.mjs at build time. Edit src/site.ts, not this file.',
          '# Feeds: WordPress served RSS at /feed/; readers follow a 301.',
          '/feed /rss.xml 301',
          '/feed/ /rss.xml 301',
          '/feed/* /rss.xml 301',
          '/comments/feed/ /rss.xml 301',
          '/category/:cat/feed/ /rss.xml 301',
          '/tag/:tag/feed/ /rss.xml 301',
          '/*/feed/ /rss.xml 301',
          '# Old category archives → the five sections (PLAN.md).',
          '/category/podcast/ /podcasts/ 301',
          '/category/podcast/* /podcasts/ 301',
        ];
        for (const s of SECTIONS) {
          for (const c of s.categories) {
            lines.push(`/category/${c.path}/ /section/${s.id}/ 301`);
            lines.push(`/category/${c.path}/* /section/${s.id}/ 301`);
          }
        }
        lines.push(
          '# Other WordPress archives.',
          '/author/* /about/ 301',
          '/page/* /archive/ 301',
          '/tag/:tag/page/* /tag/:tag/ 301',
          '/wp-login.php / 302',
          '/wp-admin/* / 302',
        );
        await fs.writeFile(new URL('_redirects', dir), lines.join('\n') + '\n');
        await fs.writeFile(
          new URL('_headers', dir),
          [
            '/*',
            '  X-Content-Type-Options: nosniff',
            '  Referrer-Policy: strict-origin-when-cross-origin',
            '  Permissions-Policy: interest-cohort=()',
            '/_astro/*',
            '  Cache-Control: public, max-age=31536000, immutable',
            '# Preview deployments must not compete with the real domain in search results.',
            'https://:project.pages.dev/*',
            '  X-Robots-Tag: noindex',
            'https://:version.:project.pages.dev/*',
            '  X-Robots-Tag: noindex',
            '',
          ].join('\n'),
        );
        console.log(`cloudflare-redirects: wrote ${lines.filter((l) => !l.startsWith('#')).length} rules to ${fileURLToPath(new URL('_redirects', dir))}`);
      },
    },
  };
}

export default defineConfig({
  site: 'https://musingsofmy.today',
  // WordPress URLs all end in a slash; keep them byte-identical.
  trailingSlash: 'always',
  build: { format: 'directory' },
  // WordPress already curled the quotes ("wptexturize"); don't do it twice.
  markdown: { smartypants: false },
  integrations: [mdx(), cloudflareRedirects()],
});
